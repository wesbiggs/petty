// 8 rows of 6-bit values, bit 5 = leftmost pixel.
export const FONT6 = Array.from({ length: 128 }, (_, code) => {
  const rows = G[code] ?? at(1, '#####', '#...#', '#...#', '#...#', '#...#', '#####'); // missing: box
  return Array.from({ length: 8 }, (_, y) => {
    const r = (rows[y] ?? '......').padEnd(6, '.');
    return [...r].reduce((v, c) => (v << 1) | (c === '#' ? 1 : 0), 0);
  });
});
