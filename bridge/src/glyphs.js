// Glyphs expressed as the inverse of another glyph.
const INVERSES = {
  '█': ' ', '▐': '▌', '▄': '▀', '▟': '▘', '▙': '▝', '▜': '▖', '▛': '▗',
};

const table = new Map();

function asciiCode(ch) {
  const c = ch.charCodeAt(0);
  if (c >= 0x20 && c <= 0x3f) return c;
  if (ch === '@') return 0;
  if (c >= 0x41 && c <= 0x5a) return c; // A-Z -> 65-90
  if (c >= 0x61 && c <= 0x7a) return c - 0x60; // a-z -> 1-26
  if (ch === '[') return 27;
  if (ch === ']') return 29;
  return undefined;
}

for (let c = 0x20; c < 0x7f; c++) {
  const ch = String.fromCharCode(c);
  const code = asciiCode(ch);
  if (code !== undefined) table.set(ch, code);
}
for (const [slot, ch] of CUSTOM_GLYPHS) table.set(ch, slot);
for (const [from, to] of Object.entries(ALIASES)) table.set(from, table.get(to));
for (const [from, to] of Object.entries(INVERSES)) table.set(from, table.get(to) | INVERSE);

const cache = new Map();
const UNKNOWN = asciiCode('?');

// Characters that --charset gives a screen code of their own (charset.js), or
// null. Set while the connected client is one that has loaded them.
let overrides = null;
export function setOverrides(map) {
  overrides = map?.size ? map : null;
  cache.clear();
}

// The screen code --charset gave this text, or undefined.
export const ownCode = chars => overrides?.get(chars);

// Map a terminal cell's text (one grapheme, may be '' for blank) to a screen code.
export function toScreenCode(chars) {
  if (chars === '' || chars === ' ') return SPACE;
  const own = overrides?.get(chars);
  if (own !== undefined) return own;
  let code = table.get(chars);
  if (code !== undefined) return code;
  code = cache.get(chars);
  if (code !== undefined) return code;
  // Strip accents (é -> e), else fall back to '?'.
  const base = chars.normalize('NFD').replace(/[̀-ͯ]/g, '');
  code = overrides?.get(base[0]) ?? table.get(base[0]) ?? UNKNOWN;
  cache.set(chars, code);
  return code;
}

// Reverse lookup used by the preview/test decoder.
export function screenCodeToChar(code) {
  const inv = code & INVERSE;
  code &= 0x7f;
  for (const [ch, c] of table) if (c === code && ch.length === 1) return inv && code === SPACE ? '█' : ch;
  return '?';
}
