// 8 rows of 4-bit values, bit 3 = leftmost pixel.
export const FONT4 = Array.from({ length: 128 }, (_, code) => {
  const rows = G[code] ?? at(1, '###', '#.#', '#.#', '#.#', '#.#', '###'); // missing: box
  return Array.from({ length: 8 }, (_, y) => {
    const r = (rows[y] ?? '....').padEnd(4, '.');
    return [...r].reduce((v, c) => (v << 1) | (c === '#' ? 1 : 0), 0);
  });
});
