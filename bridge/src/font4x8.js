// 4x8 font for the C64's soft 80-column screen, indexed by the bridge's
// screen codes 0-127 (see glyphs.js; 128-255 are the inverse). Letters are 3
// pixels wide with a gap column; N, #, lines and blocks use all 4 (N and #
// are unreadable in 3, and lines must join). Capitals and digits use rows
// 1-6, lowercase x-height rows 3-6, descenders row 7. `make` turns this into
// c64/font4x8.inc.

